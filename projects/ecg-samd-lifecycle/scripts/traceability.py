"""Generate a matrix only when every declared link names an executed passing test."""
import argparse
import json
from pathlib import Path
import subprocess
import sys
import xml.etree.ElementTree as ET


def read_junit(path):
    results = {}
    for case in ET.parse(path).getroot().iter('testcase'):
        node = case.attrib['classname'].replace('.', '/') + '.py::' + case.attrib['name']
        if node in results:
            raise ValueError(f'duplicate JUnit test: {node}')
        results[node] = ('failed' if case.find('failure') is not None or case.find('error') is not None
                         else 'skipped' if case.find('skipped') is not None else 'passed')
    if not results:
        raise ValueError('empty JUnit execution evidence')
    return results


def collect_tests():
    result = subprocess.run([sys.executable, '-m', 'pytest', '--collect-only', '-q'],
                            capture_output=True, text=True, timeout=60)
    if result.returncode:
        raise ValueError('test collection failed: ' + result.stdout[-3000:] + result.stderr[-1000:])
    return {line.strip() for line in result.stdout.splitlines() if line.startswith('tests/') and '::' in line}


def validate(spec, collected, results):
    requirements = spec.get('requirements', [])
    risks = spec.get('risks', [])
    if not requirements or not risks:
        raise ValueError('requirements and risks must be nonempty')
    ids = set()
    req_ids = {r['id'] for r in requirements}
    req_tests = {r['id']: set(r.get('tests', [])) for r in requirements}

    def check(item):
        identifier = item['id']
        if identifier in ids:
            raise ValueError(f'duplicate ID: {identifier}')
        ids.add(identifier)
        tests = item.get('tests', [])
        if not tests:
            raise ValueError(f'{identifier}: no verifying test')
        for test in tests:
            if test not in collected:
                raise ValueError(f'{identifier}: test does not exist: {test}')
            if results.get(test) != 'passed':
                raise ValueError(f'{identifier}: test did not pass: {test}')

    for requirement in requirements:
        check(requirement)
    for risk in risks:
        if risk['id'] in ids:
            raise ValueError(f"duplicate ID: {risk['id']}")
        ids.add(risk['id'])
        if not risk.get('controls'):
            raise ValueError(f"{risk['id']}: no risk controls")
        for control in risk['controls']:
            check(control)
            links = control.get('requirements', [])
            if not links or not set(links) <= req_ids:
                raise ValueError(f"{control['id']}: unknown or absent requirement link")
            linked_tests = set().union(*(req_tests[link] for link in links))
            if not set(control['tests']) <= linked_tests:
                raise ValueError(f"{control['id']}: verifying test is not linked to its requirements")
    if set(results) != collected:
        raise ValueError('execution evidence does not cover exactly the collected tests')
    if any(value != 'passed' for value in results.values()):
        raise ValueError('the full suite must pass without skipped tests')


def render_matrix(spec):
    lines = ['# Generated traceability matrix', '',
             'Generated by `uv run python -m scripts.traceability --junit build/junit.xml`.',
             'Each listed test was collected and passed. See the verification report for run identity.', '',
             '| Requirement | Acceptance criterion | Verifying tests |', '| --- | --- | --- |']
    for requirement in spec['requirements']:
        tests = '<br>'.join(f'`{node}`' for node in requirement['tests'])
        lines.append(f"| {requirement['id']} | {requirement['description'].replace('|', '/')} | {tests} |")
    lines += ['', '| Risk | Control | Requirement | Verifying tests |', '| --- | --- | --- | --- |']
    for risk in spec['risks']:
        for control in risk['controls']:
            tests = '<br>'.join(f'`{node}`' for node in control['tests'])
            lines.append(f"| {risk['id']} | {control['id']}: {control['description']} | "
                         f"{', '.join(control['requirements'])} | {tests} |")
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--spec', type=Path, default=Path('docs/lifecycle.json'))
    parser.add_argument('--junit', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path('build/traceability.md'))
    args = parser.parse_args()
    args.output.unlink(missing_ok=True)
    try:
        spec = json.loads(args.spec.read_text())
        validate(spec, collect_tests(), read_junit(args.junit))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(render_matrix(spec))
    except (ValueError, KeyError, OSError, ET.ParseError) as error:
        parser.exit(1, f'Traceability failed: {error}\n')
    print(f"Traceability: {len(spec['requirements'])} requirements and "
          f"{sum(len(r['controls']) for r in spec['risks'])} controls verified")


if __name__ == '__main__':
    main()
