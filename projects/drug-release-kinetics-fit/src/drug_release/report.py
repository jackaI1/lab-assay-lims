"""Self-contained HTML, GitHub-readable Markdown and strict JSON, no network assets."""

import html
import json
import tempfile
from pathlib import Path

import numpy as np

from .models import predict

COLORS = ["#136f63", "#bc4b19", "#6454a4", "#8b286b", "#1a6690"]


def _number(value):
    return "unavailable" if value is None else f"{value:.5g}"


def _plot(report, scope):
    t, y = np.array(report["time"]), np.array(report["fraction"])
    indices = scope["indices"]
    if not indices:
        return '<svg xmlns="http://www.w3.org/2000/svg"/>'
    xmax = max(t[indices])
    x = lambda v: 65 + 650 * v / xmax  # noqa: E731
    z = lambda v: 290 - 220 * v  # noqa: E731
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 850 570" '
        'role="img" aria-label="Release fits and residuals">',
        '<rect width="850" height="570" fill="white"/>',
        '<g font-family="sans-serif" font-size="13" fill="#17252a">',
        '<path d="M65 50V290H730 M65 350V510H730 M65 430H730" fill="none" stroke="#aaa"/>',
        '<text x="65" y="25">Fraction released (0 to 1)</text>',
        '<text x="65" y="330">Residuals: observed minus fitted (percentage points)</text>',
    ]
    for v in [0, 0.2, 0.4, 0.6, 0.8, 1]:
        out.append(f'<text x="25" y="{z(v):.1f}">{v:g}</text>')
    for v in np.linspace(0, xmax, 6):
        out.append(f'<text x="{x(v):.1f}" y="535">{v:.2g}</text>')
    out.append(f'<text x="310" y="560">Time ({html.escape(report["source"]["time_unit"])})</text>')
    residual_max = max([1] + [abs(r) for m in scope["models"].values() for r in m["residuals_pp"]])
    out.append(
        f'<text x="7" y="360">+{residual_max:.2g}</text>'
        f'<text x="7" y="505">-{residual_max:.2g}</text><text x="35" y="435">0</text>'
    )
    for j, (name, result) in enumerate(scope["models"].items()):
        color = COLORS[j]
        grid = np.linspace(min(t[indices]), xmax, 160)
        values = predict(name, grid, list(result["parameters"].values()))
        # Never draw Peppas beyond its 60% predicted release limit.
        limit = 0.6 if name == "korsmeyer_peppas" else 1.0
        points = " ".join(f"{x(a):.2f},{z(b):.2f}" for a, b in zip(grid, values) if b <= limit)
        out.append(f'<polyline points="{points}" fill="none" stroke="{color}" stroke-width="2"/>')
        out.append(f'<text x="75" y="{45 + j * 17}" fill="{color}">{name}</text>')
        for a, r in zip(t[indices], result["residuals_pp"]):
            out.append(
                f'<circle cx="{x(a):.2f}" cy="{430 - r / residual_max * 70:.2f}" '
                f'r="3" fill="{color}"/>'
            )
    for i in indices:
        shape = "rect" if i in scope["test_indices"] else "circle"
        if shape == "rect":
            out.append(
                f'<rect x="{x(t[i]) - 3:.2f}" y="{z(y[i]) - 3:.2f}" width="6" '
                'height="6" fill="#111"/>'
            )
        else:
            out.append(f'<circle cx="{x(t[i]):.2f}" cy="{z(y[i]):.2f}" r="3" fill="#111"/>')
    out.append('<text x="490" y="25">Squares: held-out observations</text></g></svg>')
    return "".join(out)


def _generate_report(report, output):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    esc = html.escape
    meta = report["source"]
    title = meta["title"]
    parts = [
        f"<h1>{esc(title)}</h1>",
        "<p>Fits describe this curve. Lower held-out RMSE means smaller prediction errors; "
        "lower AICc balances fit and model size. Compare only within the same scope. "
        "No automatic winner is declared.</p>",
        f'<p>Source: <a href="{esc(meta["source_url"], quote=True)}">'
        f"{esc(meta.get('citation', meta['source_url']))}</a></p>",
        f"<p>{esc(meta['extraction'])}</p><p>{esc(meta['error_description'])}</p>",
        f"<p>Bootstrap draws: {report['bootstrap']}; seed: {report['seed']}. "
        "Intervals are conditional 95% percentile intervals.</p>",
    ]
    md = [
        f"# {title}",
        "",
        "Generated by the command in README.md. No automatic winner is declared.",
        "",
        f"Source: [{meta.get('citation', 'paper')}]({meta['source_url']})",
        "",
        meta["extraction"],
        "",
        meta["error_description"],
        "",
        f"Bootstrap draws: {report['bootstrap']}; seed: {report['seed']}.",
        "",
    ]
    all_warnings = report["warnings"]
    parts.append(
        "<h2>Limits and source notes</h2><ul>"
        + "".join(f"<li>{esc(w)}</li>" for w in all_warnings)
        + "</ul>"
    )
    md += ["## Limits and source notes", ""] + ["- " + w for w in all_warnings] + [""]
    for i, scope in enumerate(report["scopes"]):
        svg = _plot(report, scope)
        (output / f"scope-{i}.svg").write_text(svg)
        parts += [
            f"<h2>{esc(scope['label'])}</h2>",
            f"<p>Observed points: {len(scope['indices'])}; training: "
            f"{len(scope['train_indices'])}; held-out: {len(scope['test_indices'])}. "
            "Scores use the listed scope; parameters and intervals refit all its points.</p>",
            svg,
            "<table><thead><tr><th>Model</th><th>Held-out RMSE (pp)</th>"
            "<th>AIC</th><th>AICc</th><th>Parameters [95% interval]</th>"
            "<th>Bootstrap successes</th></tr></thead><tbody>",
        ]
        md += [
            f"## {scope['label']}",
            "",
            f"Points: {len(scope['indices'])}; train: {len(scope['train_indices'])}; "
            f"held-out: {len(scope['test_indices'])}. Parameters refit all scope points.",
            "",
            f"![Fits and residuals](scope-{i}.svg)",
            "",
            "| Model | Held-out RMSE (pp) | AIC | AICc | Parameters [95% interval] | Bootstrap successes |",
            "|---|---:|---:|---:|---|---:|",
        ]
        warnings = list(scope["warnings"])
        for name, result in scope["models"].items():
            parameters = []
            for j, (key, value) in enumerate(result["parameters"].items()):
                ci = result["ci95"][j] if result["ci95"] else None
                interval = ", ".join(_number(v) for v in ci) if ci else "unavailable"
                parameters.append(f"{key}={_number(value)} [{interval}]")
            cells = [
                name,
                _number(result["heldout_rmse_pp"]),
                _number(result["aic"]),
                _number(result["aicc"]),
                "; ".join(parameters),
                str(result["bootstrap_success"]),
            ]
            parts.append("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in cells) + "</tr>")
            md.append("| " + " | ".join(cells) + " |")
            warnings.extend(f"{name}: {w}" for w in result["warnings"])
        parts += ["</tbody></table><ul>"] + [f"<li>{esc(w)}</li>" for w in warnings] + ["</ul>"]
        md += [""] + ["- " + w for w in warnings] + [""]
    parts += [
        "<h2>Reading this report</h2><p>AICc uses all scope points and includes residual "
        "variance in its parameter count. Held-out fits use only training points, before "
        "refitting. Unresolved comparisons are warnings, not equivalence tests. "
        "See docs/methods.md for equations, units, bootstrap assumptions and split rules.</p>",
        f"<p>{esc(meta.get('license', 'Source license not specified'))}</p>",
    ]
    document = '<!doctype html><html lang="en"><meta charset="utf-8">'
    document += '<meta name="viewport" content="width=device-width, initial-scale=1">'
    document += f"<title>{esc(title)}</title><style>"
    document += (
        "body{font:16px/1.6 system-ui;color:#17252a;max-width:1050px;margin:2rem auto;"
        "padding:0 1rem}table{border-collapse:collapse;display:block;overflow-x:auto}"
        "th,td{padding:.5rem;border:1px solid #ccd3d3;text-align:left}"
        "svg{width:100%;height:auto}a{color:#136f63}li{margin:.5rem 0}"
        "</style><main>" + "".join(parts) + "</main></html>"
    )
    (output / "report.html").write_text(document)
    (output / "report.md").write_text("\n".join(md))
    (output / "fit.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")


def write_report(report, output):
    """Stage complete artifacts; restore existing files if installation fails.

    This protects against ordinary I/O exceptions, not process interruption or power loss.
    Other files in the output directory are preserved.
    """
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".release-fit-", dir=output.parent) as temp:
        stage = Path(temp) / "new"
        backup = Path(temp) / "previous"
        backup.mkdir()
        _generate_report(report, stage)
        output.mkdir(parents=True, exist_ok=True)
        installed, saved = [], []
        try:
            for artifact in sorted(stage.iterdir()):
                target = output / artifact.name
                if target.exists() or target.is_symlink():
                    if target.is_dir():
                        raise ValueError(f"Report artifact is a directory: {target}")
                    target.replace(backup / artifact.name)
                    saved.append(artifact.name)
                artifact.replace(target)
                installed.append(artifact.name)
        except (OSError, ValueError):
            for name in installed:
                (output / name).unlink()
            for name in saved:
                (backup / name).replace(output / name)
            raise
